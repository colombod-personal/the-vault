# The shared facts the chair gathers once (SKILL.md, "Facts first") and hands to every member.
FACTS = ("deck_stats", "simulate_draws", "deck_legality", "find_combos", "check_decklist", "get_deck_overlap")
LOOKUPS_PER_POINT = 3  # members write at most three points (agents/*.md): at most this many card or rule lookups, an upper bound

# Tool calls each member's own brief tells it to make (fixed ones), counted from agents/<name>.md "How you work", for a
# deck review. `lookups` are the card or rule lookups the member makes per point, at most three points.
MEMBER_CALLS = {
    "vault-commander-expert": {"fixed": ["deck_legality", "deck_stats", "find_combos", "simulate_draws"], "lookups": 0},
    "vault-casual-table": {"fixed": ["deck_stats", "find_combos"], "lookups": LOOKUPS_PER_POINT},
    "vault-judge": {"fixed": ["get_card_oracle", "get_rulings", "search_rules", "get_rule", "verify_citation"], "lookups": 0},
    "vault-devils-advocate": {"fixed": ["validate_deck_changes"], "lookups": LOOKUPS_PER_POINT},
    "vault-synergy-analyst": {"fixed": ["deck_stats", "find_combos", "search_cards", "check_decklist"], "lookups": LOOKUPS_PER_POINT},
    "vault-collection-analyst": {"fixed": ["check_decklist", "get_deck_overlap", "find_upgrades", "shopping_list"], "lookups": 0},
}
RULES_TOOLS = {"search_rules", "get_rule", "verify_citation", "get_rulings"}  # answers not measured here (live Wizards text)

WORDS = ("creature artifact permanent opponent graveyard library battlefield counter target damage mana spell token "
         "attacks blocks enters leaves dies draw discard exile sacrifice destroy return control untap tap").split()


def fixture_text(rng, n):
    return " ".join(rng.choice(WORDS) for _ in range(n)).capitalize() + "."


