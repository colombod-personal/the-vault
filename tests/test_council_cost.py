def measure_answers(w):
    """tool name -> characters of the answer a host hands the model, one measured call each, on the fixture deck."""
    bot, token, deck, text = w["bot"], w["token"], w["deck"], w["text"]
    first = w["spells"][0]
    plan = {"cuts": [w["spells"][-1]["name"]], "adds": [w["extra"]["name"]]}

    def run(tool, **args):
        res = call_tool(bot, token, tool, **args)
        assert not res.get("isError"), (tool, res)
        return len(res["content"][0]["text"])

    out = {
        "list_decks": run("list_decks", query="fixture swarm"),
        "get_deck": run("get_deck", deck_id=deck["id"]),
        "deck_stats": run("deck_stats", deck_id=deck["id"]),
        "simulate_draws": run("simulate_draws", deck_id=deck["id"], format="commander"),
        "deck_legality": run("deck_legality", deck_id=deck["id"], format="commander"),
        "find_combos": run("find_combos", deck_id=deck["id"]),
        "check_decklist": run("check_decklist", text=text),
        "get_deck_overlap": run("get_deck_overlap"),
        "validate_deck_changes": run("validate_deck_changes", deck_id=deck["id"], format="commander", budget_usd=50, **plan),
        "find_upgrades": run("find_upgrades", deck_id=deck["id"], format="commander", budget_usd=10, limit=10),
        "shopping_list": run("shopping_list", deck_id=deck["id"]),
        "search_cards": run("search_cards", query="fixture", limit=10),
        "get_card_oracle": run("get_card_oracle", name=first["name"]),
    }
    return out


def tokens(chars):
    return round(chars / 4)


def cost_table(sizes):
    """The markdown for docs/expert-council.md, computed from the flows and the measured answer sizes."""
    seated = [m["id"] for m in experts.seat("commander", "tune it", budget=True)]
    chair_calls = ["list_decks", "get_deck", *FACTS, "validate_deck_changes"]
    chair_chars = sum(sizes[t] for t in chair_calls)
    facts_chars = sum(sizes[t] for t in FACTS)
    rows, total_calls, total_calls_shared, total_chars, total_chars_shared, total_brief = [], 0, 0, 0, 0, 0
    for member in seated:
        spec = MEMBER_CALLS[member]
        fixed = spec["fixed"]
        shared = [t for t in fixed if t not in FACTS]
        measured_fixed = [t for t in fixed if t not in RULES_TOOLS]
        chars = sum(sizes[t] for t in measured_fixed) + spec["lookups"] * sizes["get_card_oracle"]
        chars_shared = sum(sizes[t] for t in shared if t not in RULES_TOOLS) + spec["lookups"] * sizes["get_card_oracle"]
        n, n_shared = len(fixed) + spec["lookups"], len(shared) + spec["lookups"]
        brief = len(experts.brief(member)["brief"])
        rows.append((member, n, n_shared, chars, chars_shared, brief, any(t in RULES_TOOLS for t in fixed)))
        total_calls += n
        total_calls_shared += n_shared
        total_chars += chars
        total_chars_shared += chars_shared
        total_brief += brief
    chair_brief = len(experts.DATA["chair"]["brief"])
    lines = [
        BEGIN,
        "",
        f"Measured for a Commander deck review (\"tune it on a budget\"): the panel the seating rules pick is "
        f"{', '.join(f'`{m}`' for m in seated)} ({len(seated)} members) and the chair. Tokens are characters divided by 4.",
        "",
        "| Who | Tool calls as its brief says | Tool calls if it reuses the chair's facts | Tool answers read (tokens) as briefed | Tool answers read (tokens) reusing the facts | Brief (tokens) |",
        "|---|---|---|---|---|---|",
        f"| chair (`expert-council`) | {len(chair_calls)} | {len(chair_calls)} | {tokens(chair_chars)} | {tokens(chair_chars)} | {tokens(chair_brief)} |",
    ]
    for member, n, n_shared, chars, chars_shared, brief, rules in rows:
        lines.append(f"| `{member}`{' (+ rules answers, not measured)' if rules else ''} | {n} | {n_shared} | {tokens(chars)} | {tokens(chars_shared)} | {tokens(brief)} |")
    lines.append(f"| **Run** | **{len(chair_calls) + total_calls}** | **{len(chair_calls) + total_calls_shared}** | "
                 f"**{tokens(chair_chars + total_chars)}** | **{tokens(chair_chars + total_chars_shared)}** | **{tokens(chair_brief + total_brief)}** |")
    lines += [
        "",
        "Measured answers (tokens, one call each, on the fixture deck): " + ", ".join(
            f"`{t}` {tokens(sizes[t])}" for t in sorted(sizes)) + f". The chair hands every member the shared facts (`deck_stats` to "
        f"`get_deck_overlap`, together {tokens(facts_chars)} tokens), which each member's context then holds as well: "
        f"{tokens(facts_chars)} tokens in each of the {len(seated)} members' contexts, {tokens(facts_chars) * len(seated)} across the run, "
        "on top of the table. The lists passed as arguments (`check_decklist` takes the whole deck list) are not counted. "
        "Commander Spellbook's answer (`find_combos`) is the twin's, so a real one can be longer.",
        "",
        f"Counting rules: a member's fixed calls are the tools named in its brief's \"How you work\"; members that look at cards "
        f"(casual table, devil's advocate, synergy analyst) make at most {LOOKUPS_PER_POINT} `get_card_oracle` lookups, one per "
        "point (they write at most three points), counted at the measured size of one answer. The judge's rules answers "
        "(`get_rulings`, `search_rules`, `get_rule`, `verify_citation`) are counted as calls but not sized: the rules are read live "
        "from Wizards and no copy exists to measure.",
        "",
        END,
    ]
    return "\n".join(lines)


def test_the_cost_table_in_the_design_doc_is_what_the_flows_and_the_answers_measure(world):
    sizes = measure_answers(world)
    table = cost_table(sizes)
    text = DOC.read_text(encoding="utf-8").replace("\r\n", "\n")
    if os.environ.get("UPDATE_COUNCIL_COST"):
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        DOC.write_text(head + table + tail, encoding="utf-8")
        text = DOC.read_text(encoding="utf-8")
    assert BEGIN in text and END in text, "docs/expert-council.md has no cost section"
    assert table in text, "the doc's cost table is out of date: UPDATE_COUNCIL_COST=1 pytest tests/test_council_cost.py\n" + table


def test_every_call_counted_for_a_member_is_one_its_brief_names_and_its_definition_allows():
    """The counts come from the briefs: each counted tool is one the agent may call and its brief names; a member that is
    counted lookups writes at most three points, so the count is an upper bound; the panel is made of counted members."""
    agents = {a["name"]: a for a in bp.load_agents()}
    for member, spec in MEMBER_CALLS.items():
        body = " ".join(agents[member]["body"].split())
        assert set(spec["fixed"]) <= set(agents[member]["tools"]), member
        assert all(f"`{t}`" in body for t in spec["fixed"]), (member, [t for t in spec["fixed"] if f"`{t}`" not in body])
        assert not spec["lookups"] or "at most three" in body.lower()
        assert not spec["lookups"] or "get_card_oracle" in agents[member]["tools"]
    for goal in ("tune it", "is it legal", "explain the plan"):
        assert {m["id"] for m in experts.seat("commander", goal, budget=True)} <= set(MEMBER_CALLS)
