"""What an expert council run costs (#103): tool calls and the size of what the tools answer, measured here, and the
table in docs/expert-council.md ("Cost of one run") kept equal to what this measures, so no figure in the doc is invented.

What is measured: a Commander deck review ("tune it on a budget"), the flow in skills/expert-council/SKILL.md and each
seated member's own brief (agents/*.md). The calls are counted from those texts; the answers are real MCP answers of this
server (JSON-RPC ``tools/call``, the text a host hands the model) on a fixture catalog: a synthetic 100-card Commander deck
whose card texts are invented and about 150 characters long, prices and roles invented. Tokens are characters divided by 4,
an estimate, not a tokenizer. What is NOT measured and the doc says so: the model's own output, money, the Comprehensive
Rules answers (read live from Wizards, nothing to measure against here), and Commander Spellbook's answer (the twin's).

Update the doc after a change with:  UPDATE_COUNCIL_COST=1 pytest tests/test_council_cost.py
"""

